CREATE TABLE IF NOT EXISTS cardtypes (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(50) NOT NULL UNIQUE,
    description text NOT NULL DEFAULT '',
    sortorder integer NOT NULL,
    code text UNIQUE
);

ALTER TABLE cardtypes
    ADD COLUMN IF NOT EXISTS description text NOT NULL DEFAULT '',
    ADD COLUMN IF NOT EXISTS code text;

CREATE TABLE IF NOT EXISTS cardalignments (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(50) NOT NULL UNIQUE,
    description text NOT NULL,
    imageurl varchar(255) NOT NULL DEFAULT ''
);

CREATE TABLE IF NOT EXISTS cards (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(100) NOT NULL,
    type varchar(50) NOT NULL,
    alignment varchar(50) NOT NULL,
    ability varchar(150) NOT NULL,
    description text NOT NULL,
    imageurl varchar(255) NOT NULL,
    cardtypeid integer NOT NULL REFERENCES cardtypes(id),
    cardalignmentid integer NOT NULL REFERENCES cardalignments(id)
);

CREATE TABLE IF NOT EXISTS users (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    login varchar(32) NOT NULL UNIQUE,
    password varchar(255) NOT NULL,
    role varchar(16) NOT NULL
);

